import type { PreloadManifest, PreloadResource } from './types.js';

export type { PreloadManifest, PreloadResource, ResourceType } from './types.js';

export type PrefetchOptions = {
  /** `prefetch` warms the cache for the next navigation. Default: `prefetch` */
  rel?: 'prefetch' | 'preload';
  /** Must match how the SPA requests its assets; Vite uses `crossorigin` (anonymous). Default: `anonymous` */
  crossOrigin?: 'anonymous' | 'use-credentials' | null;
  /** Skip prefetching when the user enabled Data Saver or is on 2G. Default: `true` */
  respectSaveData?: boolean;
  /** Wait for the page `load` event and browser idle time. Default: `true` */
  waitForIdle?: boolean;
  /** Options passed to `fetch` for the manifest */
  fetchOptions?: RequestInit;
};

type NetworkInformation = { saveData?: boolean; effectiveType?: string };

function isConstrainedNetwork() {
  const connection = (navigator as Navigator & { connection?: NetworkInformation }).connection;
  return Boolean(connection?.saveData || /(^|-)2g$/.test(connection?.effectiveType ?? ''));
}

function whenIdle() {
  return new Promise<void>(resolve => {
    const schedule = () => {
      if ('requestIdleCallback' in window) window.requestIdleCallback(() => resolve(), { timeout: 2000 });
      else setTimeout(resolve, 200);
    };
    if (document.readyState === 'complete') schedule();
    else window.addEventListener('load', schedule, { once: true });
  });
}

/** Resolves resource URLs: relative `base` is resolved against the manifest URL. */
export function resolveResourceUrls(manifest: PreloadManifest, manifestUrl: string): string[] {
  const baseUrl = new URL(manifest.base || './', new URL(manifestUrl, document.baseURI));
  return manifest.resources.map(resource => new URL(resource.href, baseUrl).href);
}

function createLink(href: string, resource: PreloadResource, options: PrefetchOptions) {
  const link = document.createElement('link');
  link.rel = options.rel ?? 'prefetch';
  link.href = href;
  if (resource.as) link.as = resource.as;
  // Images are requested without CORS by the SPA, so the attribute would cause a cache mismatch
  const crossOrigin = options.crossOrigin === undefined ? 'anonymous' : options.crossOrigin;
  if (crossOrigin && resource.as !== 'image') link.crossOrigin = crossOrigin;
  return link;
}

/**
 * Fetches the manifest generated by `vite-plugin-preload-chunks` and adds `<link rel="prefetch">`
 * for every resource. Returns the URLs that were added.
 */
export async function prefetchFromManifest(manifestUrl: string, options: PrefetchOptions = {}): Promise<string[]> {
  if (typeof document === 'undefined') return [];
  if (options.respectSaveData !== false && isConstrainedNetwork()) return [];
  if (options.waitForIdle !== false) await whenIdle();

  const response = await fetch(manifestUrl, options.fetchOptions);
  if (!response.ok) throw new Error(`Failed to load preload manifest: ${response.status} ${manifestUrl}`);
  const manifest: PreloadManifest = await response.json();

  const existing = new Set(
    Array.from(document.querySelectorAll<HTMLLinkElement>('link[href]'), link => link.href),
  );
  const urls = resolveResourceUrls(manifest, response.url || manifestUrl);
  const added: string[] = [];

  urls.forEach((href, index) => {
    if (existing.has(href)) return;
    document.head.appendChild(createLink(href, manifest.resources[index], options));
    added.push(href);
  });

  return added;
}
